function formatQuestionSet(questionSet) {

  return questionSet.map(q => {

    const newOptions = q.options.map((opt, index) => {
      return `${'ABCD'[index]}. ${opt}`;
    });

    const answerMap = {};

    q.options.forEach((opt, index) => {
      answerMap[opt] = `${'ABCD'[index]}. ${opt}`;
    });

    return {
      ...q,
      options: newOptions,
      answer: q.answer.map(a => answerMap[a] || a)
    };
  });

}